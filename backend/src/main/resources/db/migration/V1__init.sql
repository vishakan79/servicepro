-- PostgreSQL schema (Neon). Written for PostgreSQL 14+; H2 in PostgreSQL mode accepts it too (dev profile and tests).
-- Schema for the feature-package domain model. Column names follow Spring's default naming
-- (camelCase field -> snake_case column); `ddl-auto: validate` fails startup if they drift.

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(255) NOT NULL,
  email         VARCHAR(255) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  phone         VARCHAR(20)  NULL,
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
  approval_pending BOOLEAN NOT NULL DEFAULT FALSE,
  role          VARCHAR(20)  NOT NULL,
  customer_id   BIGINT NULL,
  technician_id BIGINT NULL,
  enabled       BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMP(6) NOT NULL,
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT uq_users_phone UNIQUE (phone)
);

CREATE TABLE refresh_tokens (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL,
  token_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMP(6) NOT NULL,
  revoked    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uq_refresh_hash UNIQUE (token_hash),
  CONSTRAINT fk_refresh_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX ix_refresh_user ON refresh_tokens (user_id);

CREATE TABLE customers (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(255) NOT NULL,
  phone      VARCHAR(255) NOT NULL,
  email      VARCHAR(255) NOT NULL,
  address    VARCHAR(255) NOT NULL,
  area       VARCHAR(255) NULL,
  created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE technicians (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           VARCHAR(255) NOT NULL,
  title          VARCHAR(255) NOT NULL,
  skills         VARCHAR(255) NOT NULL,
  rating         DECIMAL(2,1) NOT NULL,
  completed_jobs INT NOT NULL,
  on_leave       BOOLEAN NOT NULL DEFAULT FALSE,
  phone          VARCHAR(255) NOT NULL,
  created_at     TIMESTAMP(6) NOT NULL
);

ALTER TABLE users ADD CONSTRAINT fk_users_customer FOREIGN KEY (customer_id) REFERENCES customers (id);
ALTER TABLE users ADD CONSTRAINT fk_users_technician FOREIGN KEY (technician_id) REFERENCES technicians (id);

CREATE TABLE parts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          VARCHAR(255) NOT NULL,
  name          VARCHAR(255) NOT NULL,
  category      VARCHAR(255) NOT NULL,
  brand         VARCHAR(255) NOT NULL,
  stock         INT NOT NULL,
  reorder_level INT NOT NULL,
  unit_price    DECIMAL(12,2) NOT NULL,
  CONSTRAINT uq_parts_code UNIQUE (code),
  CONSTRAINT ck_parts_stock CHECK (stock >= 0)
);

CREATE TABLE service_requests (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL,
  issue_type  VARCHAR(255) NOT NULL,
  priority    VARCHAR(10)  NOT NULL,
  status      VARCHAR(20)  NOT NULL,
  description VARCHAR(2000) NOT NULL,
  image_count INT NOT NULL,
  created_by  VARCHAR(255) NOT NULL,
  created_at  TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_sr_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);
CREATE INDEX ix_sr_customer ON service_requests (customer_id);
CREATE INDEX ix_sr_status ON service_requests (status);

CREATE TABLE work_orders (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id     BIGINT NOT NULL,
  customer_id    BIGINT NOT NULL,
  service_type   VARCHAR(255) NOT NULL,
  priority       VARCHAR(10)  NOT NULL,
  status         VARCHAR(20)  NOT NULL,
  technician_id  BIGINT NULL,
  scheduled_date DATE NOT NULL,
  start_hour     INT NOT NULL,
  duration_hours INT NOT NULL,
  description    VARCHAR(2000) NOT NULL,
  notes          VARCHAR(500) NULL,
  sla_due_at     TIMESTAMP(6) NOT NULL,
  sla_breached   BOOLEAN NOT NULL DEFAULT FALSE,
  started_at     TIMESTAMP(6) NULL,
  completed_at   TIMESTAMP(6) NULL,
  created_at     TIMESTAMP(6) NOT NULL,
  updated_at     TIMESTAMP(6) NOT NULL,
  version        BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_wo_request FOREIGN KEY (request_id) REFERENCES service_requests (id),
  CONSTRAINT fk_wo_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT fk_wo_tech FOREIGN KEY (technician_id) REFERENCES technicians (id)
);
CREATE INDEX ix_wo_status ON work_orders (status);
CREATE INDEX ix_wo_tech_date ON work_orders (technician_id, scheduled_date);
CREATE INDEX ix_wo_customer ON work_orders (customer_id);
CREATE INDEX ix_wo_sla ON work_orders (sla_due_at);

CREATE TABLE work_order_events (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_order_id BIGINT NOT NULL,
  label         VARCHAR(255) NOT NULL,
  actor         VARCHAR(255) NOT NULL,
  at            TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_evt_wo FOREIGN KEY (work_order_id) REFERENCES work_orders (id)
);
CREATE INDEX ix_evt_wo ON work_order_events (work_order_id);

CREATE TABLE checklist_items (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_order_id BIGINT NOT NULL,
  label         VARCHAR(255) NOT NULL,
  done          BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order    INT NOT NULL,
  CONSTRAINT fk_chk_wo FOREIGN KEY (work_order_id) REFERENCES work_orders (id)
);
CREATE INDEX ix_chk_wo ON checklist_items (work_order_id);

CREATE TABLE work_logs (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_order_id BIGINT NOT NULL,
  text          VARCHAR(1000) NOT NULL,
  author        VARCHAR(255) NOT NULL,
  at            TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_log_wo FOREIGN KEY (work_order_id) REFERENCES work_orders (id)
);
CREATE INDEX ix_log_wo ON work_logs (work_order_id);

CREATE TABLE part_usages (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_order_id BIGINT NOT NULL,
  part_id       BIGINT NOT NULL,
  quantity      INT NOT NULL,
  unit_price    DECIMAL(12,2) NOT NULL,
  CONSTRAINT fk_pu_wo FOREIGN KEY (work_order_id) REFERENCES work_orders (id),
  CONSTRAINT fk_pu_part FOREIGN KEY (part_id) REFERENCES parts (id),
  CONSTRAINT ck_pu_qty CHECK (quantity > 0)
);
CREATE INDEX ix_pu_wo ON part_usages (work_order_id);

CREATE TABLE invoices (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_order_id   BIGINT NOT NULL,
  customer_id     BIGINT NOT NULL,
  status          VARCHAR(10) NOT NULL,
  issued_on       DATE NOT NULL,
  due_on          DATE NOT NULL,
  payment_method  VARCHAR(255) NULL,
  transaction_ref VARCHAR(255) NULL,
  created_at      TIMESTAMP(6) NOT NULL,
  CONSTRAINT uq_inv_wo UNIQUE (work_order_id),
  CONSTRAINT fk_inv_wo FOREIGN KEY (work_order_id) REFERENCES work_orders (id),
  CONSTRAINT fk_inv_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);
CREATE INDEX ix_inv_customer ON invoices (customer_id);

CREATE TABLE invoice_lines (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id  BIGINT NOT NULL,
  description VARCHAR(255) NOT NULL,
  quantity    INT NOT NULL,
  unit_price  DECIMAL(12,2) NOT NULL,
  CONSTRAINT fk_line_inv FOREIGN KEY (invoice_id) REFERENCES invoices (id)
);
CREATE INDEX ix_line_inv ON invoice_lines (invoice_id);

CREATE TABLE feedback (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_order_id BIGINT NOT NULL,
  customer_id   BIGINT NOT NULL,
  stars         INT NOT NULL,
  comment       VARCHAR(1000) NULL,
  created_at    TIMESTAMP(6) NOT NULL,
  CONSTRAINT uq_fb_wo UNIQUE (work_order_id),
  CONSTRAINT fk_fb_wo FOREIGN KEY (work_order_id) REFERENCES work_orders (id),
  CONSTRAINT fk_fb_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT ck_fb_stars CHECK (stars BETWEEN 1 AND 5)
);

CREATE TABLE audit_logs (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor     VARCHAR(255) NOT NULL,
  action    VARCHAR(255) NOT NULL,
  entity    VARCHAR(255) NOT NULL,
  entity_id BIGINT NULL,
  detail    VARCHAR(255) NULL,
  at        TIMESTAMP(6) NOT NULL
);
CREATE INDEX ix_audit_entity ON audit_logs (entity, entity_id);
CREATE INDEX ix_audit_at ON audit_logs (at);
