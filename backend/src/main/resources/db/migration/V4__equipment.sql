-- Customer equipment with warranty and AMC (annual maintenance contract) dates.
CREATE TABLE equipment (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   BIGINT        NOT NULL REFERENCES customers (id),
  name          VARCHAR(120)  NOT NULL,
  category      VARCHAR(60)   NULL,
  brand_model   VARCHAR(120)  NULL,
  serial_no     VARCHAR(80)   NULL,
  install_date  DATE          NULL,
  warranty_until DATE         NULL,
  amc_until     DATE          NULL,
  next_service  DATE          NULL,
  notes         VARCHAR(500)  NULL,
  created_at    TIMESTAMP(6)  NOT NULL
);
CREATE INDEX idx_equipment_customer ON equipment (customer_id);
CREATE INDEX idx_equipment_next ON equipment (next_service);
